from typing import Any, Optional
import mistune

class JiraWikiMarkupRenderer(mistune.BaseRenderer):
    """
    Jira Wiki Markup Renderer for Mistune 3.x.
    
    This version is fully compliant with the Mistune 3.x API, ensuring
    correct rendering by using token-based processing.
    """
    NAME = 'jira'

    def __init__(self):
        super().__init__()
        # Deactivated for less verbose logging
        # print("Initialized JiraWikiMarkupRenderer for Mistune 3.x")
        # print("Mistune version:", mistune.__version__)

    def render_children(self, token: dict, state: Any) -> str:
        """Helper to render child tokens."""
        children = token.get('children', [])
        return "".join(self.iter_tokens(children, state))

    def heading(self, token: dict, state: Any) -> str:
        level = token['level']
        text = self.render_children(token, state)
        return f"h{level}. {text}\n\n"

    def paragraph(self, token: dict, state: Any) -> str:
        text = self.render_children(token, state)
        return f"{text}\n\n"

    def block_text(self, token: dict, state: Any) -> str:
        # block_text can be generated by plugins, e.g. task_lists
        text = self.render_children(token, state)
        return text

    def block_code(self, token: dict, state: Any) -> str:
        code = token.get('raw', '').rstrip()
        return f"{{noformat}}\n{code}\n{{noformat}}\n\n"

    def block_quote(self, token: dict, state: Any) -> str:
        text = self.render_children(token, state).rstrip()
        return f"{{quote}}\n{text}\n{{quote}}\n\n"

    def list(self, token: dict, state: Any) -> str:
        text = self.render_children(token, state)
        attrs = token.get('attrs', {})
        ordered = attrs.get('ordered', False)
        level = attrs.get('level', 1)
        
        marker = "#" if ordered else "*"
        bullet = marker * level
        
        return text.replace("@JIRA_LI@", bullet) + "\n"

    def list_item(self, token: dict, state: Any) -> str:
        text = self.render_children(token, state).rstrip()
        # Use a placeholder that the parent list will replace
        return f"@JIRA_LI@ {text}\n"

    def strong(self, token: dict, state: Any) -> str:
        text = self.render_children(token, state)
        return f"*{text}*"

    def emphasis(self, token: dict, state: Any) -> str:
        text = self.render_children(token, state)
        return f"_{text}_"

    def codespan(self, token: dict, state: Any) -> str:
        text = token.get('raw', '')
        return f"{{{{{text}}}}}"

    def linebreak(self, token: dict, state: Any) -> str:
        return "\\\\\\n" # This is a hard break in Jira Wiki Markup

    def softbreak(self, token: dict, state: Any) -> str:
        return " " # Soft breaks are just spaces in Jira Wiki Markup

    def link(self, token: dict, state: Any) -> str:
        text = self.render_children(token, state)
        attrs = token.get('attrs', {})
        url = attrs.get('url', '')
        
        if not text or text == url:
            return f"[{url}]"
        return f"[{text}|{url}]"

    def image(self, token: dict, state: Any) -> str:
        attrs = token.get('attrs', {})
        url = attrs.get('url', '')
        return f"!{url}!"

    def table(self, token: dict, state: Any) -> str:
        return self.render_children(token, state)

    def table_head(self, token: dict, state: Any) -> str:
        return self.render_children(token, state)

    def table_body(self, token: dict, state: Any) -> str:
        return self.render_children(token, state)

    def table_row(self, token: dict, state: Any) -> str:
        return self.render_children(token, state) + "|\n"

    def table_cell(self, token: dict, state: Any) -> str:
        text = self.render_children(token, state)
        attrs = token.get('attrs', {})
        separator = "||" if attrs.get('head') else "|"
        return f"{separator}{text}"

    def thematic_break(self, token: dict, state: Any) -> str:
        return "----\n\n"

    def strikethrough(self, token: dict, state: Any) -> str:
        text = self.render_children(token, state)
        return f"-{text}-"
    
    def task_list_item(self, token: dict, state: Any) -> str:
        attrs = token.get('attrs', {})
        checked = attrs.get('checked', False)
        text = self.render_children(token, state).rstrip()

        if checked:
            checkbox_display = "(/)"
            rendered_text = f"-{text}-" # Durchgestrichener Text
        else:
            checkbox_display = "[ ]"
            rendered_text = text
        
        # Verwendet den gleichen Platzhalter-Mechanismus wie list_item
        return f"@JIRA_LI@ {checkbox_display} {rendered_text}\n"

    def text(self, token: dict, state: Any) -> str:
        return token.get('raw', '')

    def blank_line(self, token: dict, state: Any) -> str:
        """Handle blank lines in the document."""
        return "\n"

    def final_render(self, tokens: list, state: Any) -> str:
        rendered = super().final_render(tokens, state)
        if "@JIRA_LI@" in rendered:
            return rendered.replace("@JIRA_LI@", "*")
        return rendered